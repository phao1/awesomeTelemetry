import unittest
from inventory import Inventory
from inventory.export import total,pivot,reconcile
from inventory.csv_input import write

class Workflows(unittest.TestCase):
    def test_append_workflow_0(self):
        x=Inventory()
        rows=[
            {'id':'a','revision':0,'at':'2025-01-01T00:00:00Z','sku':'widget','warehouse':'east','quantity':1},
            {'id':'b','revision':0,'at':'2025-01-01T00:00:00Z','sku':'widget','warehouse':'east','quantity':2},
        ]
        self.assertEqual(x.ingest(rows),2)
        self.assertEqual(x.ingest(rows),0)
        first=x.day('2025-01-01')
        self.assertEqual(total(first),'3')
        self.assertEqual(first[0]['count'],2)
        first[0]['quantity']='mutated'
        self.assertEqual(total(x.day('2025-01-01')),'3')
        snapshot=x.checkpoint()
        y=Inventory()
        y.restore(snapshot)
        self.assertEqual(y.day('2025-01-01'),x.day('2025-01-01'))
        self.assertEqual(x.correct('a',quantity=4),1)
        self.assertEqual(total(x.day('2025-01-01')),'6')
        self.assertEqual(len(x.history('a')),2)
        x.delete('b')
        self.assertEqual(total(x.day('2025-01-01')),'4')
        z=Inventory()
        self.assertEqual(z.ingest_csv(write(rows)),2)
        self.assertEqual(total(z.day('2025-01-01')),'3')
        self.assertEqual(reconcile(y.day('2025-01-01'),x.day('2025-01-01')),[{'warehouse':'east','sku':'widget','delta':'1'}])
        report=pivot({'2025-01-01':x.day('2025-01-01')})
        self.assertEqual(report[0]['days'],{'2025-01-01':'4'})
